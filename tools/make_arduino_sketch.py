#!/usr/bin/env python3
"""Generate flat Arduino sketches from the single source tree (never edit the output).

  python3 tools/make_arduino_sketch.py

Writes
  firmware/arduino/TinyBuddy/     Arduino IDE sketch (SH1106 default; USB CDC On Boot: Enabled)
  firmware/arduino/wokwi_web/     upload these files to a wokwi.com ESP32-C3 project (SSD1306)
"""
from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "core" / "src"
FW = ROOT / "firmware" / "src"
OUT = ROOT / "firmware" / "arduino"

HEADER = "// GENERATED by tools/make_arduino_sketch.py from core/src + firmware/src - do not edit.\n"


def bundle(dest: Path, ino: str, defines: dict[str, str], extra: dict[str, str]) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for src in sorted(list(CORE.glob("*.h")) + list(CORE.glob("*.cpp")) + list(FW.glob("*.h")) + list(FW.glob("*.cpp"))):
        text = src.read_text()
        name = src.name
        if name == "main.cpp":
            name = ino
        if name == "Config.h" and defines:
            pre = "".join(f"#define {k} {v}\n" for k, v in defines.items())
            text = text.replace("#pragma once\n", "#pragma once\n" + pre, 1)
        (dest / name).write_text(HEADER + text)
    for name, text in extra.items():
        (dest / name).write_text(text)


def main() -> None:
    bundle(OUT / "TinyBuddy", "TinyBuddy.ino", {}, {
        "README.txt": "Arduino IDE: install 'esp32 by Espressif' (2.0.x or 3.x) and library 'U8g2'.\n"
                      "Board: ESP32C3 Dev Module, USB CDC On Boot: Enabled. Open TinyBuddy.ino, upload.\n"
                      "Controller default SH1106 (1.3\" modules); type `display ssd1306` in the Serial Monitor if needed.\n"})
    bundle(OUT / "wokwi_web", "sketch.ino", {"TB_DEFAULT_CONTROLLER": "0", "TB_WOKWI": "1"}, {
        "libraries.txt": "# Wokwi library manager\nU8g2\n",
        "diagram.json": (ROOT / "firmware" / "diagram.json").read_text(),
    })
    print("wrote", (OUT / "TinyBuddy").relative_to(ROOT), "and", (OUT / "wokwi_web").relative_to(ROOT))


if __name__ == "__main__":
    main()
